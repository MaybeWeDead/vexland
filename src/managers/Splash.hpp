#pragma once

extern "C" {
#include <xcb/xcb.h>
}

// -----------------------------------------------------------------------
// Splash.hpp — временная цитата внизу экрана по центру, видна ~30
// секунд после старта, затем плавно исчезает (fade-out). Рендерится
// через BitmapFont.hpp (свой 5x7 pixel font, без Xft/fontconfig — см.
// обсуждение в чате про riск Xlib/XCB моста). Встраивается в
// VXR::repaint() как ещё один слой поверх фона, под окнами.
//
// Список фраз зашит в Splash.cpp (аналог SPLASHES vector у Hyprland —
// намеренно НЕ читается из конфига/файла: цитаты не редактируются
// пользователем, см. обсуждение "не должны настраиваться, но можно
// выключить целиком"). Отключается через general.disable_splash в
// конфиге.
// -----------------------------------------------------------------------

namespace Splash {

// Выбирает случайную фразу (99% обычная, 1% редкая пасхалка) и
// запоминает момент показа — вызывается один раз при старте
// (см. Compositor::init, после VXR::init).
void init();

// true, пока splash должен быть виден (включая fade-out период) —
// используется VXR::repaint() чтобы решить, рисовать ли его вообще
// в этом кадре. false после того как истекли и видимость, и fade.
bool isActive();

// Текущая alpha (0.0-1.0) для fade-out — 1.0 всё время показа, потом
// плавно к 0.0 в последние FADE_DURATION секунд. VXR использует это
// как множитель альфы при composite.
float currentAlpha();

const char* text();

} // namespace Splash
