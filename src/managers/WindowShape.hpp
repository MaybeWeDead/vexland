#include "../desktop/view/Window.hpp"

// -----------------------------------------------------------------------
// WindowShape.hpp — скругление углов окна через X11 Shape extension
// (XCB_SHAPE), БЕЗ compositing и БЕЗ picom. Аналог decoration.rounding
// из Hyprland-конфига, только там это делает сам компоновщик через
// рендер поверх surface; у нас, поскольку мы X11 core WM без
// собственного compositing-рендерера, это делается через
// xcb_shape_mask — серверная маска формы окна, применяемая один раз
// (и пересчитываемая при каждом resize, т.к. маска привязана к
// конкретным пиксельным размерам окна).
//
// Аппроксимация: НЕ настоящая bitmap-маска пиксель-в-пиксель (это
// требовало бы либо готового pixmap с альфой, либо генерации круга
// вручную через Брезенхэма — оверкилл для рамки в 6-12px). Вместо
// этого — "лестничная" аппроксимация через несколько прямоугольников
// на угол (staircase corner), классический трюк лёгких X11 WM
// (см. compton/xcompmgr-эры до появления настоящего blur). На малых
// радиусах (<=12px) с 3-4 ступеньками разница на глаз почти незаметна.
// -----------------------------------------------------------------------

namespace WindowShape {

// Применяет скруглённую маску к окну. radius в пикселях; 0 = убрать
// маску (вернуть окно к обычному прямоугольнику через xcb_shape_mask
// с SET и пустым/полным regionом).
void applyRounding(xcb_connection_t* conn, PHLWINDOW w, int radius);

// Проверка доступности Shape extension на сервере — вызывается один
// раз при старте (см. Compositor::init). Если сервер её не поддерживает
// (крайне маловероятно, extension'у больше 30 лет, но проверка дешёвая
// и защищает от кримта на экзотических X-серверах вроде Xvfb с
// урезанной сборкой) — applyRounding будет молча no-op.
bool queryShapeExtension(xcb_connection_t* conn);

} // namespace WindowShape
